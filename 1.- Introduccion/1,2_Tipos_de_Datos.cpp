/*1.2 Tipos de datos basicos de C++*/

//Librerias
 #include <iostream>

//Le indico al programa que usare una salida stadar (std) de datos
 using namespace std;
 
//Inicio del programa
 int main(){

	//Declaracion de variables locales
	/*Tipo de dato numerico*/	int entero = 15;
	/*Tipo de dato decimal*/	float flotante = 10.45;
	/*Tipo de dato double*/		double mayor = 16.3454;
	/*Tipo de dato caracter*/	char letra = 'l';
	
	cout << entero << endl;
	cout << flotante << endl;
	cout << mayor << endl;
	cout << letra << endl;

	//Fin del programa
	return 1;
}

